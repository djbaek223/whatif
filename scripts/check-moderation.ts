const failures: string[] = [];
for (const [text, kind] of BLOCKED) {
  const got = moderate(text);
  if (got !== kind) failures.push(`should block (${kind}) but got ${got}: ${JSON.stringify(text)} → ${JSON.stringify(normalizeForModeration(text))}`);
}
for (const text of ALLOWED) {
  const got = moderate(text);
  if (got) failures.push(`should allow but blocked (${got}): ${JSON.stringify(text)} → ${JSON.stringify(normalizeForModeration(text))}`);
}
if (composeJamo("ㅅㅔㄱㅅㅡ") !== "섹스") failures.push(`composeJamo("ㅅㅔㄱㅅㅡ") = ${composeJamo("ㅅㅔㄱㅅㅡ")}`);

