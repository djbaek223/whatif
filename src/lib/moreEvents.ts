import type { EventDef } from "./events";
import type { LifeState } from "./types";

const year = (s: LifeState) => Math.floor(s.mi / 12);
const month = (s: LifeState) => (s.mi % 12) + 1;
const inYears = (from: number, to = from) => (s: LifeState) => year(s) >= from && year(s) <= to;
const kidAges = (s: LifeState) => (s.flags.kidsBorn ?? []).map((b) => Math.floor((s.mi - b) / 12));
const hasKidAged = (lo: number, hi = lo) => (s: LifeState) => kidAges(s).some((a) => a >= lo && a <= hi);
const single = (s: LifeState) => s.flags.partner === "none" || s.flags.partner === "divorced" || s.flags.partner === "widowed";
const married = (s: LifeState) => s.flags.partner === "married";
const student = (s: LifeState) => s.flags.education === "school" || s.flags.education === "highschool";
const working = (s: LifeState) => s.flags.employed && !s.flags.retired;
const civil = (s: LifeState) => /공무원/.test(s.flags.job);
/** Months since a chain step happened; -1 when it never did. */
const ago = (s: LifeState, mark: string) => (s.marks?.[mark] === undefined ? -1 : s.mi - s.marks[mark]);

const NAMES = ["민수", "지영", "현우", "수진", "성호", "은정", "재훈", "미경", "동현", "혜원", "준호", "선영"];
const FAMILY = ["김", "이", "박", "최", "정", "강", "조", "윤"];

/** A stable name for someone in this life (the classmate, the mentor), so later events and the narrator name the same person. */
function nameFor(s: LifeState, role: string): string {
  let h = 0;
  for (const ch of `${s.profile.birthDate}|${s.turningPoint.date}|${s.profile.name}|${role}`) h = (Math.imul(h, 31) + ch.charCodeAt(0)) | 0;
  h = Math.abs(h);
  return `${FAMILY[h % FAMILY.length]}${NAMES[Math.floor(h / FAMILY.length) % NAMES.length]}`;
}

const hasFinal = (word: string) => {
  const code = (word.at(-1) ?? "").charCodeAt(0) - 0xac00;
  return code >= 0 && code <= 11171 && code % 28 !== 0;
};
/** 이/가 and 와/과 after a Korean name, by its final consonant. */
const iGa = (word: string) => `${word}${hasFinal(word) ? "이" : "가"}`;
const waGwa = (word: string) => `${word}${hasFinal(word) ? "과" : "와"}`;

