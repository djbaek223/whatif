// More routine lines for a quiet month (engine statusLines): by stage of life, by kind of work, by who is at home,
// and by season. Each list is added to the engine's own lines for that stage, so a life moves through many small
// scenes instead of the same few. Lines that only make sense in Korea (학원, 복날, 벌초) are in `kr(...)` and left out
// of an American life; the rest are told so they fit either country. Lines naming something modern (휴대폰, 메일)
// are dropped in years that didn't have it by the engine's period check (period.ts), like every other routine line.
import type { CompanyTier } from "./catalog";
import { L } from "./i18n";
import { isUS } from "./region";

/** Lines for a Korean life only. */
const kr = (...lines: string[]) => (isUS() ? [] : lines);

/** A few more lines for each month, on top of the engine's SEASON. */
export function seasonMore(month: number): string[] {
  switch (month) {
    case 1: return [L("새해 계획을 수첩 첫 장에 또박또박 적었다."), L("한파에 수도관이 얼까 봐 물을 조금 틀어 두고 잤다."), L("신년 운세를 읽으며 좋은 말만 골라 믿었다.")];
    case 2: return [L("졸업식 시즌, 꽃다발 가게 앞이 북적였다."), L("겨울의 끝자락, 바람 끝이 조금 순해졌다."), L("밸런타인데이 초콜릿이 가게 앞을 가득 채웠다.")];
    case 3: return [L("꽃샘추위에 넣어 둔 두꺼운 외투를 다시 꺼냈다."), L("겨울옷을 정리하고 봄옷을 꺼냈다."), ...kr(L("황사에 하늘이 하루 종일 뿌옇게 흐렸다."))];
    case 4: return [L("꽃구경 나온 사람들 틈에 섞여 천천히 걸었다."), L("봄맞이 대청소로 주말이 다 갔다."), ...kr(L("식목일에 베란다에 화분 하나를 들였다."))];
    case 5: return [L("초여름 같은 햇살에 반팔을 꺼내 입었다."), L("스승의 날, 문득 옛 선생님 생각이 났다."), ...kr(L("어린이날, 놀이공원은 사람으로 발 디딜 틈이 없었다."))];
    case 6: return [L("수박 한 통을 낑낑대며 들고 집에 왔다."), L("해가 길어져 저녁 산책이 늘었다."), ...kr(L("현충일 아침, 사이렌 소리에 잠시 멈춰 섰다."))];
    case 7: return [L("장맛비에 우산이 마를 날이 없었다."), L("모기와의 여름 전쟁이 시작되었다."), ...kr(L("복날, 삼계탕 한 그릇으로 더위를 넘겼다."))];
    case 8: return [L("휴가철, 고속도로가 주차장처럼 막혔다."), L("계곡물에 발을 담그고 수박을 먹었다."), L("태풍 소식에 창문 단속을 했다.")];
    case 9: return [L("개학하고 거리가 다시 분주해졌다."), L("늦더위가 좀처럼 물러가지 않았다."), ...kr(L("벌초하러 고향 산소에 다녀왔다."))];
    case 10: return [L("길가에 코스모스가 한들거렸다."), L("등산로가 단풍 구경 인파로 붐볐다."), L("운동회 함성이 학교 담장을 넘어왔다.")];
    case 11: return [L("낙엽 밟는 소리가 바스락거렸다."), L("올겨울 처음으로 난방을 켰다."), ...kr(L("수능 날, 거리가 조용했고 듣기 평가 동안은 비행기도 멈췄다."))];
    case 12: return [L("송년회 약속이 줄줄이 잡혔다."), L("창밖에서 크리스마스 불빛이 반짝였다."), L("달력의 마지막 장을 넘겼다.")];
    default: return [];
  }
}

