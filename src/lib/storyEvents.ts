/**
 * Months since a chapter of the life began, or -1 when it hasn't: "job", "business", "jobless", "retired", "promoted",
 * "dating", "married", "breakup", "divorced", "widowed", "child", "home", "school", "graduated" (marked by the engine
 * when the life changes), "discharged" (from the service dates), or a chain's own "ch:" mark ("abroad", "night-school").
 */
export function sinceChapter(s: LifeState, chapter: string): number {
  if (chapter === "discharged") {
    const until = s.flags.serviceUntil;
    return until !== undefined && s.mi >= until ? s.mi - until : -1;
  }
  const at = s.marks?.[`ch:${chapter}`];
  return at === undefined ? -1 : s.mi - at;
}

const year = (s: LifeState) => Math.floor(s.mi / 12);
const month = (s: LifeState) => (s.mi % 12) + 1;
const kidAges = (s: LifeState) => (s.flags.kidsBorn ?? []).map((b) => Math.floor((s.mi - b) / 12));
const hasKidAged = (lo: number, hi = lo) => (s: LifeState) => kidAges(s).some((a) => a >= lo && a <= hi);
const married = (s: LifeState) => s.flags.partner === "married";
const single = (s: LifeState) => s.flags.partner !== "dating" && s.flags.partner !== "married";
const student = (s: LifeState) => s.flags.education === "school" || (s.flags.education === "highschool" && !retaking(s));
const working = (s: LifeState) => s.flags.employed && !s.flags.retired;
const civil = (s: LifeState) => /공무원/.test(s.flags.job);
const parentsAlive = (s: LifeState) => !s.done.includes("parent-death");

